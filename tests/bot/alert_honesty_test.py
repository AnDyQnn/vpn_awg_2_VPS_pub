# -*- coding: utf-8 -*-
"""Тревоги о нагрузке говорят правду.

Владельцу пришло «она упала и высокая нагрузка», а на узле в этот момент было
0–4% процессора, средняя нагрузка 0.06 и свежее рукопожатие. Ни падения, ни
нагрузки.

Виновато было две вещи сразу:

  • Недоступность объявлялась по ОДНОМУ неудачному запросу. Хватало занятого
    агента, снятия копии или секундной заминки в туннеле.

  • Заголовок у сообщения был один на всё — «Критическая нагрузка». Поэтому
    «агент не ответил» читалось как «упал И перегружен» разом.

Плюс сам порог нагрузки брался с мгновенного замера, а он скачет до сотни от
ночной проверки обновлений.

Тревога, которая врёт, хуже отсутствующей: её перестают читать вместе с
настоящими.
"""
import sys

sys.path.insert(0, "/app")

import monitor                                     # noqa: E402

ok = True


def check(name, cond, detail=""):
    global ok
    ok = ok and cond
    print("  %s %-54s %s" % ("•" if cond else "ПРОВАЛ:", name, detail))


print("=== когда узел считается перегруженным ===")
# Одно ядро: очередь в полтора процесса и выше — это уже разговор.
check("спокойный узел не перегружен", not monitor._overloaded(0.06, 1),
      "0.06 на ядро — ровно то, что было на живом")
check("лёгкая занятость тоже нет", not monitor._overloaded(0.9, 1))
check("устойчивая очередь — да", monitor._overloaded(2.0, 1))
check("на четырёх ядрах та же двойка — нет",
      not monitor._overloaded(2.0, 4),
      "иначе многоядерный узел ругался бы постоянно")
check("мусор не роняет проверку", not monitor._overloaded(None, 1))
check("нет данных о ядрах — считаем за одно",
      monitor._overloaded(3.0, None))

print()
print("=== одна заминка — не падение ===")
check("нужно несколько промахов подряд",
      monitor.DE_MISSES_TO_ALERT >= 3,
      "сейчас %d; проверки идут раз в пять минут" % monitor.DE_MISSES_TO_ALERT)
check("это больше четверти часа молчания",
      monitor.DE_MISSES_TO_ALERT * 300 >= 900,
      "настоящее падение столько не прячется")

print()
print("=== заголовки не смешивают разное ===")
src = open("/app/monitor.py", encoding="utf-8").read()
part = src[src.index("async def resource_monitor_loop"):]
part = part[:part.index("async def alert_loop")]
check("недоступность и нагрузка разведены",
      "down_alerts" in part and "load_alerts" in part,
      "иначе «не ответил» читается как «перегружен»")
check("у недоступности свой заголовок",
      "Узел не отвечает" in part)
# Ищем именно отправляемую строку, а не упоминание в пояснении: комментарий,
# объясняющий починку, ссылаться на прежний заголовок обязан.
code = chr(10).join(l for l in part.splitlines() if not l.lstrip().startswith("#"))
check("общего заголовка про нагрузку больше нет",
      "Критическая нагрузка" not in code,
      "он и создавал ложное «упал и перегружен»")
check("по мгновенному проценту не судим",
      "cpu_percent" not in part,
      "он скачет до сотни от ночной проверки обновлений")
check("счётчик промахов сбрасывается при ответе",
      "_de_misses = 0" in part,
      "иначе одна заминка копилась бы до тревоги через сутки")

print()
print("ВСЁ ПРОШЛО" if ok else "ЕСТЬ ПРОВАЛЫ")
sys.exit(0 if ok else 1)
