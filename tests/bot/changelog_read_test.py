# -*- coding: utf-8 -*-
"""Ченджлог должен читаться ботом: разбор версий и то, что увидит человек.

Проверка не косметическая: ченджлог показывается в боте, и ошибка разметки
или превышение предела Telegram означают пустой экран у владельца.
"""
import io

import changelog

rel = changelog.parse_releases(limit=5)
print("=== разобрано записей:", len(rel), "===")
assert rel, "ченджлог не разобрался вовсе"
print("  версии:", [r[0] for r in rel])

# Верхняя запись обязана описывать собираемую версию, иначе бот покажет
# людям изменения не от той сборки.
version = io.open("/app/VERSION_FILE", encoding="utf-8").read().strip()
assert rel[0][0] == version, (rel[0][0], version)
assert rel[1][0] != version, "две записи об одной версии"
print("верхняя — бета, следом последняя рабочая: ок")

print("\n=== что видит владелец ===")
text = changelog.admin_text()
print(" ", text[:220].replace("\n", " "), "…")
assert len(text) <= 4096, f"не влезет в сообщение: {len(text)}"
# Раньше здесь требовалось конкретное слово: так вышло, что три верхние записи
# были об одном. Это примета, а не свойство экрана — стоило верхней записи стать
# о другом, и тест падал на ровном месте. Проверяем, что экран содержателен.
assert len(text.splitlines()) >= 4, text
assert text.count("•") >= 2, "на экране должны быть пункты, а не только версии"
print("  длина", len(text), "— предел Telegram выдержан: ок")

print("\n=== что видит человек ===")
# Пустота здесь — законный ответ, а не поломка: если за промежуток не было
# ни одного раздела «Для пользователей», человеку показывать нечего, и
# кнопка «Что нового» ему просто не рисуется. Проверяем оба пути.
user = changelog.user_text()
if user is None:
    print("  нового для людей нет — это валидный ответ")
else:
    assert len(user) <= 4096, len(user)
    print("  длина", len(user), ": ок")

# А сам механизм обязан работать: с точки, откуда разделы для людей ещё
# впереди, текст быть должен. Иначе «нового нет» будет ответом всегда, и
# заметить это станет нечем.
user = changelog.user_text(since_version="0.0.1")
assert user, "механизм молчит даже там, где текст для людей есть"
assert len(user) <= 4096, len(user)
print("  с самого начала собирается:", len(user), "знаков: ок")

print("\n=== разметка не рвётся ===")
for name, body in (("владельцу", text), ("человеку", user)):
    assert body.count("**") % 2 == 0, f"{name}: непарные звёздочки"
    assert body.count("`") % 2 == 0, f"{name}: непарные кавычки"
    # Подчёркивание для телеграма — курсив, и непарное рушит СООБЩЕНИЕ
    # ЦЕЛИКОМ: экран не открывается, а выглядит это как мёртвая кнопка.
    # Экранированные (\_) не считаем — они и нужны, чтобы имена вроде
    # depends_on не ломали разметку.
    bare = body.replace(chr(92) + "_", "")
    assert bare.count("_") % 2 == 0, (
        f"{name}: непарное подчёркивание — телеграм отвергнет сообщение")
print("звёздочки и кавычки парные: ок")

print("\n=== человеку показывается то же, что владельцу ===")
# Раньше человеку доставались только пункты из раздела «Для пользователей».
# Пишем мы его не всегда — и человек видел «нового пока нет» там, где менялось
# многое. Две разные правды об одном обновлении, расходящиеся молча.
fresh = changelog.user_text(since_version="7.1.0-alpha.8")
assert fresh, "человеку нечего показать"
print(" ", fresh[:170].replace(chr(10), " "), "…")

# Текст собран тем же рендером: в нём есть номер версии и заголовки разделов.
assert "**" in fresh, "разметка заголовков потерялась"
import re as _re
assert _re.search(r"\*\*\d+\.\d+", fresh), "номера версии не видно"

# И то же самое содержимое, что у владельца: берём верхнюю запись у обоих и
# сверяем пункты. Иначе «как у админа» осталось бы обещанием.
admin_top = changelog.admin_text(limit=1)
top_ver = changelog.parse_releases(limit=1)[0][0]
user_from_prev = changelog.user_text(
    since_version=changelog.parse_releases(limit=2)[1][0])
assert user_from_prev, "верхняя запись человеку не показалась"
for chunk in ("•",):
    assert chunk in user_from_prev and chunk in admin_top
common = sum(1 for line in user_from_prev.split(chr(10))
             if line.startswith("•") and line in admin_top)
print("  общих пунктов с текстом владельца:", common)
assert common >= 1, "тексты разошлись — значит правды снова две"
print("  один текст на всех: ок")

print("\n=== прочитал всё — экран не пустеет ===")
# Раздел называется «Что нового», и открывать его человек будет не только
# после обновления. Раньше прочитавший получал окошко «Нового пока нет» —
# то есть пустоту там, где у владельца последняя запись видна всегда.
assert changelog.user_text(since_version=version) is None, (
    "накопленного быть не должно: человек видел текущую версию")
last = changelog.last_user_text()
assert last, "последняя запись для людей не нашлась"
print(" ", last[:170].replace(chr(10), " "), "…")
assert "Версия:" in last, last
assert last.count("*") % 2 == 0, "непарные звёздочки — телеграм отвергнет"
bare = last.replace(chr(92) + "_", "")
assert bare.count("_") % 2 == 0, "непарное подчёркивание"
assert len(last.splitlines()) >= 3, last
print("  последнее для людей показывается всегда: ок")

print("\nВСЁ ПРОШЛО")
